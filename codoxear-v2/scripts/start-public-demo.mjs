import { existsSync } from "node:fs";
import { spawn } from "node:child_process";
if (!existsSync("/.dockerenv")) throw new Error("Docker only");
const bridge = spawn(process.execPath, ["scripts/demo-tls-bridge.mjs", "container", "/demo-bridge"], { stdio: "inherit" });
const egress = process.env.CODOXEAR_DEMO_EGRESS_SOCKET ? spawn(process.execPath, ["scripts/demo-provider-network.mjs", "container", process.env.CODOXEAR_DEMO_EGRESS_SOCKET], { stdio: "inherit" }) : undefined;
const demo = spawn(process.execPath, ["--import", "tsx", "scripts/demo.ts"], { stdio: "inherit" });
const children = [bridge, demo, ...(egress ? [egress] : [])];
let stopping = false;
const stop = () => { if (stopping) return; stopping = true; for (const child of children) if (child.exitCode === null) child.kill("SIGTERM"); };
for (const child of children) child.once("exit", code => { if (!stopping) { process.exitCode = code || 1; stop(); } });
process.on("SIGTERM", stop); process.on("SIGINT", stop);
